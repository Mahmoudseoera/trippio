import {readFile,writeFile} from 'node:fs/promises';
import {catalogFromHTML} from '../assets/js/travel-search-core.mjs';
const root=new URL('../',import.meta.url);
const core=await readFile(new URL('assets/js/travel-search-core.mjs',root),'utf8');
const ui=await readFile(new URL('assets/js/ai-travel-search.mjs',root),'utf8');
const catalog=catalogFromHTML(await readFile(new URL('ai-assistance.html',root),'utf8'));
const bundle='// Generated by node deliverables/build-travel-search.mjs. Do not edit.\n(()=>{\n'+core.replace(/export /g,'')+'\nglobalThis.TrippioTravelCatalog='+JSON.stringify(catalog)+';\n'+ui.replace(/^import .*;\r?\n/,'')+'\n})();\n';
await writeFile(new URL('assets/js/ai-travel-search.js',root),bundle,'utf8');
let html=await readFile(new URL('ai-travel-search.html',root),'utf8');
html=html.replace('<script type="module" src="assets/js/ai-travel-search.mjs"></script>','<script defer src="assets/js/ai-travel-search.js"></script>').replace('<label for="query">','<label id="query-label" for="query">');
await writeFile(new URL('ai-travel-search.html',root),html,'utf8');
console.log('Built classic script and catalog snapshot from authored source.');
